STORAGE_SOURCE = 'https://www.foodsafety.gov/food-safety-charts/cold-food-storage-charts'


def sourced(name, slug, ingredients, minutes, diet, allergens, steps, *,
            yield_count=4, slot='main', changes='', water=0, batch=False):
    """Ingredients are the full adapted source batch, divided by yield_count."""
    ingredients = {k: round(v / yield_count, 4) for k, v in ingredients.items()}
    notes = COMMON + ' ' + changes
    if water:
        notes += ' Готовый бульон заменён водой: вкус и пищевая ценность отличаются; бульонные кубики не включены.'
        steps = ['Количество воды для основы указано отдельно рядом с ингредиентами; дополнительная вода для варки и крахмала в него не входит.'] + steps
    steps = ['Используйте количества рядом с инструкцией: в книге блюд это базовая порция, а в плане — уже рассчитанное количество на показанные порции. Повторно умножать состав плана не нужно.'] + steps
    storage = ('Охладите в неглубокой закрытой ёмкости и уберите в холодильник ≤4 °C в течение 2 часов. '
               'План предусматривает максимум 3 календарных дня, включая день готовки; перед подачей полностью прогрейте.'
               if batch else 'Готовьте к подаче; автоматическое распределение остатков на следующие дни отключено.')
    steps.append(storage)
    return dict(name=name, ingredients=ingredients, **calculate_nutrition(ingredients),
                preparation_minutes=minutes, diet=diet, allergens=allergens,
                instructions='\n'.join(f'{i + 1}. {s}' for i, s in enumerate(steps)),
                meal_slot=slot, side_dish='', batch_servings=3 if batch else 1,
                storage_days=3 if batch else 0, storage_note=storage,
                storage_source_url=STORAGE_SOURCE if batch else '',
                nutrition_status='ingredient_estimate',
                nutrition_source='USDA SR Legacy 2018; расчёт по ингредиентам',
                weight_basis='ingredients_before_cooking', recipe_source_url=NHS + slug + '/',
                recipe_source_name='NHS Healthier Families', recipe_adaptation_note=notes,
                cooking_water_ml=water / yield_count,
                max_portion_input_grams=1000 if slot == 'main' else 500,
                adapted_servings=yield_count, source_checked_at='2026-10-11')


